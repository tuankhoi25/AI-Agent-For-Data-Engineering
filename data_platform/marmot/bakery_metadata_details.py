"""Business definitions and SQL contracts for the operational bakery catalog.

Allowed values and database constraints come from the project DDL. Business
interpretations are kept separate from those database-enforced constraints.
"""

from functools import lru_cache
from pathlib import Path
import re
from typing import Any


def _sql_items(text: str) -> list[str]:
    """Split comma-separated DDL items, preserving quoted strings/parentheses."""
    parts, start, depth, quoted, index = [], 0, 0, False, 0
    while index < len(text):
        char = text[index]
        if char == "'":
            if quoted and index + 1 < len(text) and text[index + 1] == "'":
                index += 2
                continue
            quoted = not quoted
        elif not quoted:
            if char == "(": depth += 1
            elif char == ")": depth -= 1
            elif char == "," and depth == 0:
                parts.append(text[start:index].strip())
                start = index + 1
        index += 1
    parts.append(text[start:].strip())
    if quoted or depth:
        raise RuntimeError("Unbalanced SQL contract; check the project CREATE TABLE statement.")
    return [part for part in parts if part]


def _sql_group(text: str, start: int) -> tuple[str, int]:
    depth, quoted, index = 0, False, start
    while index < len(text):
        char = text[index]
        if char == "'":
            if quoted and index + 1 < len(text) and text[index + 1] == "'":
                index += 2
                continue
            quoted = not quoted
        elif not quoted:
            if char == "(": depth += 1
            elif char == ")":
                depth -= 1
                if depth == 0: return text[start + 1:index], index + 1
        index += 1
    raise RuntimeError("Unclosed SQL constraint in the project DDL.")


@lru_cache(maxsize=1)
def schema_contracts() -> dict[str, dict[str, Any]]:
    """Read actual CREATE TABLE declarations; do not infer values from sample rows."""
    root = Path(__file__).resolve().parents[2]
    contracts = {}
    type_pattern = r"(BIGINT|INTEGER|VARCHAR\(\d+\)|CHAR\(\d+\)|TEXT|DATE|TIMESTAMPTZ|NUMERIC\(\d+\s*,\s*\d+\)|BOOLEAN)"
    for path in sorted((root / "data_platform/postgres").glob("*.sql")):
        text = path.read_text(encoding="utf-8")
        match = re.search(r"CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\(", text, re.I)
        if not match or match[1] == "simulation_runs": continue
        body, _ = _sql_group(text, match.end() - 1)
        contract = {"source": str(path.relative_to(root)), "columns": {}, "primary_key": [], "unique": [], "checks": [], "foreign_keys": []}
        for declaration in _sql_items(body):
            declaration = re.sub(r"^CONSTRAINT\s+\w+\s+", "", declaration, flags=re.I)
            column = re.match(r"(\w+)\s+" + type_pattern + r"\s*(.*)$", declaration, re.I | re.S)
            if column:
                name, sql_type, suffix = column.groups()
                identity = "GENERATED BY DEFAULT AS IDENTITY" in suffix.upper()
                # BY DEFAULT is identity syntax, not a DEFAULT expression.
                default = None if identity else re.search(r"\bDEFAULT\s+(.+?)(?=\s+(?:CHECK|REFERENCES|UNIQUE|NOT NULL|PRIMARY KEY)\b|$)", suffix, re.I | re.S)
                field = {"sql_type": sql_type, "nullable": not bool(re.search(r"\bNOT NULL\b|\bPRIMARY KEY\b", suffix, re.I)), "default": default[1].strip() if default else None, "identity": identity, "checks": []}
                contract["columns"][name] = field
                if "PRIMARY KEY" in suffix.upper(): contract["primary_key"].append(name)
                if re.search(r"\bUNIQUE\b", suffix, re.I): contract["unique"].append([name])
                fk = re.search(r"REFERENCES\s+(\w+)\s*\((\w+)\)(?:\s+ON DELETE\s+(CASCADE|SET NULL|RESTRICT|NO ACTION))?", suffix, re.I)
                if fk:
                    reference = {"column": name, "schema": "bakery", "table": fk[1], "target_column": fk[2], "on_delete": (fk[3] or "NO ACTION").upper()}
                    field["references"] = reference
                    contract["foreign_keys"].append(reference)
            else:
                name, field = None, None
                keys = re.match(r"(PRIMARY KEY|UNIQUE)\s*\((.*?)\)$", declaration, re.I | re.S)
                if keys:
                    names = [part.strip() for part in _sql_items(keys[2])]
                    if keys[1].upper() == "PRIMARY KEY": contract["primary_key"] = names
                    else: contract["unique"].append(names)
                elif not declaration.upper().startswith("CHECK"):
                    raise RuntimeError(f"Unsupported declaration in {path.name}: {declaration}")
            for check in re.finditer(r"\bCHECK\s*\(", declaration, re.I):
                expression, _ = _sql_group(declaration, check.end() - 1)
                contract["checks"].append(expression)
                if field is not None:
                    field["checks"].append(expression)
                    allowed = re.fullmatch(r"\s*" + re.escape(name) + r"\s+IN\s*\((.*)\)\s*", expression, re.I | re.S)
                    if allowed:
                        field["allowed_values"] = [value.replace("''", "'") for value in re.findall(r"'((?:''|[^'])*)'", allowed[1])]
        for name, field in contract["columns"].items():
            field["primary_key_columns"] = contract["primary_key"] if name in contract["primary_key"] else []
            field["unique_groups"] = [keys for keys in contract["unique"] if name in keys]
            if name in contract["primary_key"]: field["nullable"] = False
            field["related_checks"] = [expr for expr in contract["checks"] if re.search(r"\b" + re.escape(name) + r"\b", expr)]
        contracts[match[1]] = contract
    return contracts


