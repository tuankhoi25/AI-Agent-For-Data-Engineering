def validate_details(table_names: set[str]) -> None:
    contracts = schema_contracts()
    if set(TABLE_RULES) != table_names or set(contracts) != table_names:
        raise RuntimeError("Operational table definitions, business rules and SQL contracts must cover the same tables.")
    enum_keys = set()
    for table_name, contract in contracts.items():
        for column_name, field in contract["columns"].items():
            if "allowed_values" in field:
                key = (table_name, column_name)
                enum_keys.add(key)
                if set(ENUM_MEANINGS.get(key, {})) != set(field["allowed_values"]):
                    raise RuntimeError(f"Allowed-value meanings are incomplete or differ from SQL: {table_name}.{column_name}")
        unknown = set(COLUMN_DETAILS.get(table_name, {})) - contract["columns"].keys()
        if unknown:
            raise RuntimeError(f"Unknown documented columns for {table_name}: {sorted(unknown)}")
    if enum_keys != set(ENUM_MEANINGS):
        raise RuntimeError("Documented value domains differ from the project's SQL CHECK domains.")


