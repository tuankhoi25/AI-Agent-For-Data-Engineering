def describe_mart_column(table_name: str, column_name: str, data_type: str) -> str:
    """Return a useful description without inventing a new physical contract."""
    if column_name in COMMON_COLUMN_DESCRIPTIONS:
        return COMMON_COLUMN_DESCRIPTIONS[column_name]
    if column_name.endswith("_count"):
        return "Count of records or events at the table's declared reporting grain."
    if column_name.endswith("_quantity") or column_name.endswith("_qty"):
        return "Quantity at the table's declared unit-of-measure grain."
    if column_name.endswith("_amount") or column_name.endswith("_revenue") or column_name.endswith("_sales"):
        return "Monetary KPI at the table's declared reporting grain; use the associated currency context before summing across currencies."
    if column_name.endswith("_at") or column_name.endswith("_date") or column_name in {"opened_at", "closed_at"}:
        return "Business or warehouse timestamp used by the mart's reporting logic."
    if column_name.endswith("_code") or column_name.endswith("_name"):
        return "Descriptive business attribute carried into the mart for filtering and display."
    if data_type.lower() == "boolean":
        return "Boolean business indicator calculated or carried from the upstream model."
    if "numeric" in data_type.lower() or "int" in data_type.lower() or "double" in data_type.lower():
        return "Numeric business attribute or KPI at the table's declared reporting grain."
    return "Business attribute carried from an upstream dbt model; see the table grain and source-model metadata."
