SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS waste_records (
    waste_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT REFERENCES branches(branch_id),
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    inventory_lot_id BIGINT REFERENCES inventory_lots(inventory_lot_id),
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    reason_code VARCHAR(30) NOT NULL CHECK (reason_code IN ('EXPIRED','DAMAGED','QUALITY','UNSOLD','PRODUCTION_LOSS','OTHER')),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    recorded_by BIGINT REFERENCES employees(employee_id),
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT waste_records_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT waste_records_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON waste_records
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN waste_records._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN waste_records._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN waste_records._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN waste_records._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';

