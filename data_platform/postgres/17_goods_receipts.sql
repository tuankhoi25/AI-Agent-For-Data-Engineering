SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS goods_receipts (
    goods_receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR(50) NOT NULL UNIQUE,
    purchase_order_id BIGINT REFERENCES purchase_orders(purchase_order_id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(supplier_id),
    branch_id BIGINT REFERENCES branches(branch_id),
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    received_by BIGINT REFERENCES employees(employee_id),
    supplier_invoice_number VARCHAR(80),
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT goods_receipts_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT goods_receipts_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON goods_receipts
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN goods_receipts._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN goods_receipts._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN goods_receipts._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN goods_receipts._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


INSERT INTO goods_receipts (receipt_number, purchase_order_id, supplier_id, branch_id, received_at, received_by, supplier_invoice_number, notes)
SELECT 'GR-' || po.po_number, po.purchase_order_id, po.supplier_id, po.branch_id,
       (b.opening_date::timestamp + TIME '05:00') AT TIME ZONE b.timezone,
       e.employee_id, 'SIM-' || po.po_number,
       'Đã kiểm nhận trước ngày khai trương; chứng từ giả lập.'
FROM purchase_orders po
JOIN branches b ON b.branch_id=po.branch_id
LEFT JOIN employees e ON e.employee_code='EMP-001'
WHERE po.po_number IN ('PO-OPENING-PHATANAN','PO-OPENING-GOODFOOD','PO-OPENING-BEEMART','PO-OPENING-PURATOS','PO-OPENING-TAKA','PO-OPENING-LOCAL')
ON CONFLICT (receipt_number) DO UPDATE SET purchase_order_id=EXCLUDED.purchase_order_id, supplier_id=EXCLUDED.supplier_id, branch_id=EXCLUDED.branch_id, notes=EXCLUDED.notes;
