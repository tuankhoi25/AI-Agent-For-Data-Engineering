CREATE TABLE IF NOT EXISTS recipes (
    recipe_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    recipe_version VARCHAR(30) NOT NULL,
    yield_quantity NUMERIC(14,3) NOT NULL CHECK (yield_quantity > 0),
    yield_uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    effective_from DATE NOT NULL,
    effective_to DATE,
    instructions TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (product_id, recipe_version),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT recipes_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT recipes_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON recipes
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN recipes._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN recipes._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN recipes._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN recipes._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


