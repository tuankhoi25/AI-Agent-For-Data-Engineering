CREATE TABLE IF NOT EXISTS purchase_order_items (
    purchase_order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(purchase_order_id) ON DELETE CASCADE,
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    ordered_quantity NUMERIC(14,3) NOT NULL CHECK (ordered_quantity > 0),
    uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    expected_unit_cost NUMERIC(12,2) CHECK (expected_unit_cost IS NULL OR expected_unit_cost >= 0),
    notes TEXT,
    UNIQUE (purchase_order_id, stock_item_id),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT purchase_order_items_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT purchase_order_items_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON purchase_order_items
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN purchase_order_items._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN purchase_order_items._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN purchase_order_items._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN purchase_order_items._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


