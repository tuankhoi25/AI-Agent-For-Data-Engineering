SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS purchase_orders (
    purchase_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number VARCHAR(50) NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(supplier_id),
    branch_id BIGINT REFERENCES branches(branch_id),
    ordered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expected_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SENT','PARTIALLY_RECEIVED','RECEIVED','CANCELLED')),
    currency_code CHAR(3) NOT NULL DEFAULT 'VND',
    notes TEXT,
    created_by BIGINT REFERENCES employees(employee_id),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT purchase_orders_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT purchase_orders_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON purchase_orders
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN purchase_orders._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN purchase_orders._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN purchase_orders._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN purchase_orders._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


-- Đơn nhập đã nhận trước khai trương; số liệu và giá vốn là giả lập.
INSERT INTO purchase_orders (po_number, supplier_id, branch_id, ordered_at, expected_at, status, currency_code, notes, created_by)
SELECT v.po_number, s.supplier_id, b.branch_id,
       ((b.opening_date - 1)::timestamp + TIME '08:00') AT TIME ZONE b.timezone,
       (b.opening_date::timestamp + TIME '05:00') AT TIME ZONE b.timezone,
       'RECEIVED', 'VND', 'Đơn nhập giả lập cho kỳ chuẩn bị khai trương.', e.employee_id
FROM (VALUES
('PO-OPENING-PHATANAN','PHATANAN'),('PO-OPENING-GOODFOOD','GOODFOOD'),('PO-OPENING-BEEMART','BEEMART'),
('PO-OPENING-PURATOS','PURATOS_VN'),('PO-OPENING-TAKA','TAKAFOODS'),('PO-OPENING-LOCAL','LOCAL_FOOD_VENDOR')
) AS v(po_number, supplier_code)
JOIN suppliers s ON s.supplier_code=v.supplier_code
CROSS JOIN branches b
LEFT JOIN employees e ON e.employee_code='EMP-001'
WHERE b.branch_code='MAIN'
ON CONFLICT (po_number) DO UPDATE SET supplier_id=EXCLUDED.supplier_id, branch_id=EXCLUDED.branch_id, status=EXCLUDED.status, notes=EXCLUDED.notes, created_by=EXCLUDED.created_by;
