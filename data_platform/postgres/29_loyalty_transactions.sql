SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS loyalty_transactions (
    loyalty_transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    sale_id BIGINT REFERENCES sales(sale_id),
    transaction_type VARCHAR(20) NOT NULL CHECK (transaction_type IN ('EARN','REDEEM','ADJUST','EXPIRE')),
    points_delta INTEGER NOT NULL CHECK (points_delta <> 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    idempotency_key VARCHAR(120) UNIQUE,
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT loyalty_transactions_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT loyalty_transactions_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON loyalty_transactions
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN loyalty_transactions._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN loyalty_transactions._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN loyalty_transactions._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN loyalty_transactions._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';

