SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR(50) NOT NULL UNIQUE,
    branch_id BIGINT REFERENCES branches(branch_id),
    customer_id BIGINT REFERENCES customers(customer_id),
    cashier_id BIGINT REFERENCES employees(employee_id),
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('IN_STORE','TAKEAWAY','DELIVERY','ONLINE','OTHER')),
    status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED' CHECK (status IN ('OPEN','COMPLETED','CANCELLED','PARTIALLY_REFUNDED','REFUNDED')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    tax_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    idempotency_key VARCHAR(120) UNIQUE,
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT sales_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT sales_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON sales
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN sales._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN sales._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN sales._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN sales._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';

