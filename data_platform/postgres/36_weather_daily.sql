SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS weather_daily (
    weather_daily_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weather_date DATE NOT NULL,
    location_code VARCHAR(64) NOT NULL,
    location_name VARCHAR(160) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    timezone VARCHAR(60) NOT NULL,
    weather_source VARCHAR(64) NOT NULL,
    weather_model VARCHAR(80),
    source_url TEXT NOT NULL,
    temperature_mean_c NUMERIC(8,3),
    temperature_max_c NUMERIC(8,3),
    temperature_min_c NUMERIC(8,3),
    apparent_temperature_mean_c NUMERIC(8,3),
    apparent_temperature_max_c NUMERIC(8,3),
    apparent_temperature_min_c NUMERIC(8,3),
    relative_humidity_mean_pct NUMERIC(8,3),
    relative_humidity_max_pct NUMERIC(8,3),
    relative_humidity_min_pct NUMERIC(8,3),
    precipitation_sum_mm NUMERIC(12,3),
    rain_sum_mm NUMERIC(12,3),
    snowfall_sum_cm NUMERIC(12,3),
    precipitation_hours NUMERIC(8,3),
    weather_code INTEGER,
    sunrise_at TIMESTAMPTZ,
    sunset_at TIMESTAMPTZ,
    daylight_duration_seconds NUMERIC(14,3),
    sunshine_duration_seconds NUMERIC(14,3),
    wind_speed_max_kmh NUMERIC(10,3),
    wind_gusts_max_kmh NUMERIC(10,3),
    wind_direction_dominant_deg INTEGER,
    shortwave_radiation_sum_mj_m2 NUMERIC(14,3),
    api_fetched_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT weather_daily_natural_key UNIQUE (weather_date, location_code, weather_source),
    CONSTRAINT weather_daily_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT weather_daily_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE INDEX IF NOT EXISTS weather_daily_date_idx
    ON weather_daily (weather_date, location_code);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON weather_daily
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON TABLE weather_daily IS
'Daily historical weather observations fetched from Open-Meteo for bakery demand and calendar analysis. One row per date, location and source.';
COMMENT ON COLUMN weather_daily.api_fetched_at IS
'Timestamp when the external weather API response was fetched; source refresh metadata, not the weather observation time.';
COMMENT ON COLUMN weather_daily.weather_code IS
'WMO weather interpretation code returned by Open-Meteo; the most severe daily code for the selected location.';
COMMENT ON COLUMN weather_daily._created_at IS
'Database insertion time set by the row-audit trigger; not the weather date.';
COMMENT ON COLUMN weather_daily._last_updated_at IS
'Database time of the latest API payload write, used by incremental extraction.';
COMMENT ON COLUMN weather_daily._is_deleted IS
'Soft-delete flag for source correction; normally false for external daily observations.';
COMMENT ON COLUMN weather_daily._deleted_at IS
'Database time of the current soft-deletion episode, when applicable.';
