SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS supplier_products (
    supplier_product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(supplier_id),
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    supplier_sku VARCHAR(80),
    brand_name VARCHAR(120),
    purchase_uom_id BIGINT REFERENCES units_of_measure(uom_id),
    pack_size NUMERIC(14,3) CHECK (pack_size IS NULL OR pack_size > 0),
    pack_uom_id BIGINT REFERENCES units_of_measure(uom_id),
    last_known_unit_cost NUMERIC(12,2) CHECK (last_known_unit_cost IS NULL OR last_known_unit_cost >= 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'VND',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    UNIQUE (supplier_id, stock_item_id),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT supplier_products_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT supplier_products_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON supplier_products
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN supplier_products._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN supplier_products._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN supplier_products._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN supplier_products._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


