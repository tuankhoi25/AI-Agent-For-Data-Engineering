-- Tạo lô thành phẩm và số dư thành phẩm bán được tại thời điểm mở cửa.
INSERT INTO inventory_lots (stock_item_id, lot_code, manufactured_at, received_at, expires_at, notes)
SELECT p.stock_item_id, 'PROD-OPENING-' || p.sku, b.opening_date, b.opening_date,
       CASE WHEN p.sku LIKE 'BAK-ENT-%' THEN b.opening_date + 3
            WHEN p.sku LIKE 'BAK-MAC-%' OR p.sku LIKE 'RTL-MAC-%' THEN b.opening_date + 4
            ELSE b.opening_date + 1 END,
       'Lô thành phẩm chuẩn bị trước khai trương; hạn dùng mô phỏng.'
FROM production_batches pb
JOIN branches b ON b.branch_id=pb.branch_id
JOIN products p ON p.product_id=pb.product_id
WHERE pb.batch_number LIKE 'PREOPEN-%'
ON CONFLICT (stock_item_id, lot_code) DO UPDATE SET manufactured_at=EXCLUDED.manufactured_at, received_at=EXCLUDED.received_at, expires_at=EXCLUDED.expires_at, notes=EXCLUDED.notes;

INSERT INTO stock_movements (branch_id, stock_item_id, inventory_lot_id, movement_type, quantity_delta, uom_id, occurred_at, source_type, source_id, idempotency_key, created_by, notes)
SELECT b.branch_id, p.stock_item_id, il.inventory_lot_id, 'PRODUCTION_OUTPUT', pb.produced_quantity, pb.uom_id,
       pb.completed_at, 'PRODUCTION_BATCH', pb.production_batch_id, 'PROD-OUT:' || pb.batch_number, pb.produced_by, 'Thành phẩm đầu ngày.'
FROM production_batches pb
JOIN branches b ON b.branch_code='MAIN'
JOIN products p ON p.product_id=pb.product_id
JOIN inventory_lots il ON il.stock_item_id=p.stock_item_id AND il.lot_code='PROD-OPENING-' || p.sku
WHERE pb.batch_number LIKE 'PREOPEN-%'
ON CONFLICT (idempotency_key) DO NOTHING;
