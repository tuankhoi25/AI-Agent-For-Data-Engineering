CREATE TABLE IF NOT EXISTS production_batches (
    production_batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_number VARCHAR(50) NOT NULL UNIQUE,
    branch_id BIGINT REFERENCES branches(branch_id),
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    recipe_id BIGINT REFERENCES recipes(recipe_id),
    planned_quantity NUMERIC(14,3) CHECK (planned_quantity IS NULL OR planned_quantity > 0),
    produced_quantity NUMERIC(14,3) CHECK (produced_quantity IS NULL OR produced_quantity >= 0),
    uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED','IN_PROGRESS','COMPLETED','CANCELLED')),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    produced_by BIGINT REFERENCES employees(employee_id),
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT production_batches_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT production_batches_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON production_batches
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN production_batches._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN production_batches._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN production_batches._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN production_batches._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


