CREATE TABLE IF NOT EXISTS stock_items (
    stock_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_code VARCHAR(50) NOT NULL UNIQUE,
    stock_item_name VARCHAR(180) NOT NULL,
    item_type VARCHAR(30) NOT NULL CHECK (item_type IN ('RAW_MATERIAL','PACKAGING','FINISHED_GOOD','RETAIL_GOOD')),
    base_uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    track_lot BOOLEAN NOT NULL DEFAULT TRUE,
    track_expiry BOOLEAN NOT NULL DEFAULT FALSE,
    reorder_level NUMERIC(14,3) CHECK (reorder_level IS NULL OR reorder_level >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT stock_items_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT stock_items_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON stock_items
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN stock_items._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN stock_items._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN stock_items._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN stock_items._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


