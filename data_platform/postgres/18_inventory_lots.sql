SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS inventory_lots (
    inventory_lot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    lot_code VARCHAR(80) NOT NULL,
    supplier_lot_code VARCHAR(80),
    goods_receipt_id BIGINT REFERENCES goods_receipts(goods_receipt_id),
    manufactured_at DATE,
    received_at DATE,
    expires_at DATE,
    unit_cost NUMERIC(12,2) CHECK (unit_cost IS NULL OR unit_cost >= 0),
    notes TEXT,
    UNIQUE (stock_item_id, lot_code),
    CHECK (expires_at IS NULL OR manufactured_at IS NULL OR expires_at >= manufactured_at),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT inventory_lots_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT inventory_lots_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON inventory_lots
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN inventory_lots._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN inventory_lots._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN inventory_lots._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN inventory_lots._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


-- Mỗi mặt hàng đã nhận có một lô tồn mở đầu; hạn dùng là giả lập và cần thay bằng nhãn lô thật.
INSERT INTO inventory_lots (stock_item_id, lot_code, goods_receipt_id, received_at, expires_at, unit_cost, notes)
SELECT si.stock_item_id, 'RCV-OPENING-' || si.stock_item_code, gr.goods_receipt_id, b.opening_date,
       CASE WHEN si.track_expiry THEN b.opening_date + CASE
            WHEN si.stock_item_code IN ('MILK_FRESH','CREAM_ANCHOR') THEN 21
            WHEN si.stock_item_code IN ('LEMON','FRUIT_PUREE','BLUEBERRY_PUREE','ICE') THEN 14
            WHEN si.stock_item_code IN ('EGGS','BUTTER_PRESIDENT','BUTTER_ANCHOR') THEN 45
            ELSE 180 END
       ELSE NULL END,
       poi.expected_unit_cost, 'Lô nhập mở đầu mô phỏng; ngày hết hạn giả lập.'
FROM purchase_order_items poi
JOIN purchase_orders po ON po.purchase_order_id=poi.purchase_order_id
JOIN goods_receipts gr ON gr.purchase_order_id=po.purchase_order_id
JOIN branches b ON b.branch_id=po.branch_id
JOIN stock_items si ON si.stock_item_id=poi.stock_item_id
WHERE po.po_number LIKE 'PO-OPENING-%'
ON CONFLICT (stock_item_id, lot_code) DO UPDATE SET goods_receipt_id=EXCLUDED.goods_receipt_id, received_at=EXCLUDED.received_at, expires_at=EXCLUDED.expires_at, unit_cost=EXCLUDED.unit_cost, notes=EXCLUDED.notes;
