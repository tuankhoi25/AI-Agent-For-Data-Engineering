SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS goods_receipt_items (
    goods_receipt_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id BIGINT NOT NULL REFERENCES goods_receipts(goods_receipt_id) ON DELETE CASCADE,
    purchase_order_item_id BIGINT REFERENCES purchase_order_items(purchase_order_item_id),
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    inventory_lot_id BIGINT REFERENCES inventory_lots(inventory_lot_id),
    received_quantity NUMERIC(14,3) NOT NULL CHECK (received_quantity > 0),
    uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    actual_unit_cost NUMERIC(12,2) CHECK (actual_unit_cost IS NULL OR actual_unit_cost >= 0),
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT goods_receipt_items_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT goods_receipt_items_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON goods_receipt_items
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN goods_receipt_items._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN goods_receipt_items._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN goods_receipt_items._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN goods_receipt_items._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


INSERT INTO goods_receipt_items (goods_receipt_id, purchase_order_item_id, stock_item_id, inventory_lot_id, received_quantity, uom_id, actual_unit_cost, notes)
SELECT gr.goods_receipt_id, poi.purchase_order_item_id, si.stock_item_id, il.inventory_lot_id, poi.ordered_quantity, poi.uom_id, poi.expected_unit_cost,
       'Nhận đủ theo số lượng đặt; dữ liệu và giá vốn giả lập.'
FROM purchase_order_items poi
JOIN purchase_orders po ON po.purchase_order_id=poi.purchase_order_id
JOIN goods_receipts gr ON gr.purchase_order_id=po.purchase_order_id
JOIN stock_items si ON si.stock_item_id=poi.stock_item_id
JOIN inventory_lots il ON il.stock_item_id=si.stock_item_id AND il.lot_code='RCV-OPENING-' || si.stock_item_code
WHERE po.po_number LIKE 'PO-OPENING-%'
AND NOT EXISTS (
    SELECT 1 FROM goods_receipt_items gri
    WHERE gri.goods_receipt_id=gr.goods_receipt_id AND gri.stock_item_id=si.stock_item_id AND gri.inventory_lot_id=il.inventory_lot_id
);
