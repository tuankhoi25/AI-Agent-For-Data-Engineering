CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    product_name VARCHAR(180) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES product_categories(category_id),
    product_type VARCHAR(20) NOT NULL CHECK (product_type IN ('BAKERY','BEVERAGE','RETAIL','MERCH')),
    sell_uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    stock_item_id BIGINT UNIQUE REFERENCES stock_items(stock_item_id),
    description TEXT,
    ingredient_summary TEXT,
    unit_price NUMERIC(12,2) CHECK (unit_price IS NULL OR unit_price >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    available_from DATE,
    available_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (available_to IS NULL OR available_from IS NULL OR available_to >= available_from),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT products_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT products_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON products
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN products._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN products._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN products._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN products._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


