SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS stock_movements (
    stock_movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT REFERENCES branches(branch_id),
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    inventory_lot_id BIGINT REFERENCES inventory_lots(inventory_lot_id),
    movement_type VARCHAR(30) NOT NULL CHECK (movement_type IN ('PURCHASE_RECEIPT','PRODUCTION_CONSUMPTION','PRODUCTION_OUTPUT','SALE','RETURN_IN','WASTE','ADJUSTMENT_IN','ADJUSTMENT_OUT','TRANSFER_IN','TRANSFER_OUT')),
    quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
    uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    unit_cost NUMERIC(12,2) CHECK (unit_cost IS NULL OR unit_cost >= 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    source_type VARCHAR(40),
    source_id BIGINT,
    idempotency_key VARCHAR(120) UNIQUE,
    created_by BIGINT REFERENCES employees(employee_id),
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT stock_movements_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT stock_movements_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON stock_movements
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN stock_movements._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN stock_movements._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN stock_movements._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN stock_movements._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


-- Ghi sổ nhập kho cho tất cả các dòng nhận hàng.
INSERT INTO stock_movements (branch_id, stock_item_id, inventory_lot_id, movement_type, quantity_delta, uom_id, unit_cost, occurred_at, source_type, source_id, idempotency_key, created_by, notes)
SELECT gr.branch_id, gri.stock_item_id, gri.inventory_lot_id, 'PURCHASE_RECEIPT', gri.received_quantity, gri.uom_id, gri.actual_unit_cost,
       gr.received_at, 'GOODS_RECEIPT', gr.goods_receipt_id,
       'GR:' || gr.receipt_number || ':' || si.stock_item_code, gr.received_by, 'Tồn kho mở đầu từ phiếu nhận hàng giả lập.'
FROM goods_receipt_items gri
JOIN goods_receipts gr ON gr.goods_receipt_id=gri.goods_receipt_id
JOIN stock_items si ON si.stock_item_id=gri.stock_item_id
WHERE gr.receipt_number LIKE 'GR-PO-OPENING-%'
ON CONFLICT (idempotency_key) DO NOTHING;
