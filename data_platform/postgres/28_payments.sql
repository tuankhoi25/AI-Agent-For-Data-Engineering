SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(sale_id) ON DELETE CASCADE,
    payment_method VARCHAR(30) NOT NULL CHECK (payment_method IN ('CASH','CARD','BANK_TRANSFER','E_WALLET','GIFT_CARD','OTHER')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'VND',
    status VARCHAR(20) NOT NULL DEFAULT 'CAPTURED' CHECK (status IN ('PENDING','CAPTURED','FAILED','REFUNDED')),
    paid_at TIMESTAMPTZ,
    provider_reference VARCHAR(120),
    notes TEXT,
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT payments_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT payments_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON payments
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN payments._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN payments._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN payments._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN payments._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';

