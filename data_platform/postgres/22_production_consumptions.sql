SET search_path TO bakery;

CREATE TABLE IF NOT EXISTS production_consumptions (
    production_consumption_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_batch_id BIGINT NOT NULL REFERENCES production_batches(production_batch_id) ON DELETE CASCADE,
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(stock_item_id),
    inventory_lot_id BIGINT REFERENCES inventory_lots(inventory_lot_id),
    quantity_used NUMERIC(14,4) NOT NULL CHECK (quantity_used > 0),
    uom_id BIGINT NOT NULL REFERENCES units_of_measure(uom_id),
    unit_cost NUMERIC(12,2) CHECK (unit_cost IS NULL OR unit_cost >= 0),
    notes TEXT,
    UNIQUE (production_batch_id, stock_item_id, inventory_lot_id),
    _created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _last_updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    _is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    _deleted_at TIMESTAMPTZ,
    CONSTRAINT production_consumptions_audit_timestamps_check CHECK (_last_updated_at >= _created_at),
    CONSTRAINT production_consumptions_audit_deletion_check CHECK ((_is_deleted AND _deleted_at IS NOT NULL) OR (NOT _is_deleted AND _deleted_at IS NULL))
);

CREATE OR REPLACE TRIGGER bakery_row_audit
BEFORE INSERT OR UPDATE ON production_consumptions
FOR EACH ROW EXECUTE FUNCTION bakery.set_row_audit();

COMMENT ON COLUMN production_consumptions._created_at IS 'Database insertion time set by row-audit trigger; immutable after insert. Not the business event time. Existing rows receive migration adoption time.';
COMMENT ON COLUMN production_consumptions._last_updated_at IS 'Database time of the latest INSERT or UPDATE, including soft deletion and restoration; trigger-managed. Not a commit sequence or business event time.';
COMMENT ON COLUMN production_consumptions._is_deleted IS 'Soft-delete flag: false means retained in normal operations; true means logically deleted. Independent of is_active and business status; no cascading or reversal.';
COMMENT ON COLUMN production_consumptions._deleted_at IS 'Database time of the current soft-deletion episode; set when _is_deleted becomes true, preserved while true and cleared on restoration. NULL for non-deleted rows.';


-- Tiêu hao theo công thức giả lập cho từng mẻ trước ngày khai trương.
INSERT INTO production_consumptions (production_batch_id, stock_item_id, inventory_lot_id, quantity_used, uom_id, unit_cost, notes)
SELECT pb.production_batch_id, ri.stock_item_id, COALESCE(prod_lot.inventory_lot_id, raw_lot.inventory_lot_id),
       ri.quantity * pb.produced_quantity / r.yield_quantity, ri.uom_id, COALESCE(prod_lot.unit_cost, raw_lot.unit_cost),
       'Tiêu hao mô phỏng theo recipe; có thể hiệu chỉnh sau.'
FROM production_batches pb
JOIN products output_product ON output_product.product_id=pb.product_id
JOIN recipes r ON r.recipe_id=pb.recipe_id
JOIN recipe_items ri ON ri.recipe_id=r.recipe_id
JOIN stock_items input_item ON input_item.stock_item_id=ri.stock_item_id
LEFT JOIN products input_product ON input_product.stock_item_id=input_item.stock_item_id
LEFT JOIN inventory_lots prod_lot ON prod_lot.stock_item_id=input_item.stock_item_id AND prod_lot.lot_code='PROD-OPENING-' || input_product.sku
LEFT JOIN inventory_lots raw_lot ON raw_lot.stock_item_id=input_item.stock_item_id AND raw_lot.lot_code='RCV-OPENING-' || input_item.stock_item_code
WHERE pb.batch_number LIKE 'PREOPEN-%'
  AND pb.recipe_id IS NOT NULL
  AND COALESCE(prod_lot.inventory_lot_id, raw_lot.inventory_lot_id) IS NOT NULL
ON CONFLICT (production_batch_id, stock_item_id, inventory_lot_id) DO UPDATE SET quantity_used=EXCLUDED.quantity_used, uom_id=EXCLUDED.uom_id, unit_cost=EXCLUDED.unit_cost, notes=EXCLUDED.notes;

INSERT INTO stock_movements (branch_id, stock_item_id, inventory_lot_id, movement_type, quantity_delta, uom_id, unit_cost, occurred_at, source_type, source_id, idempotency_key, created_by, notes)
SELECT pb.branch_id, pc.stock_item_id, pc.inventory_lot_id, 'PRODUCTION_CONSUMPTION', -pc.quantity_used, pc.uom_id, pc.unit_cost,
       pb.completed_at, 'PRODUCTION_BATCH', pb.production_batch_id,
       'PROD-CONSUME:' || pb.batch_number || ':' || si.stock_item_code, pb.produced_by, 'Nguyên liệu/ bán thành phẩm dùng cho mẻ đầu ngày.'
FROM production_consumptions pc
JOIN production_batches pb ON pb.production_batch_id=pc.production_batch_id
JOIN stock_items si ON si.stock_item_id=pc.stock_item_id
WHERE pb.batch_number LIKE 'PREOPEN-%'
ON CONFLICT (idempotency_key) DO NOTHING;

-- Tính giá vốn đơn vị thành phẩm theo các dòng tiêu hao đã ghi; đơn vị quy đổi đều là đơn vị cơ sở.
WITH batch_costs AS (
    SELECT pb.production_batch_id, p.stock_item_id,
           SUM(pc.quantity_used * pc.unit_cost) / NULLIF(pb.produced_quantity, 0) AS unit_cost
    FROM production_batches pb
    JOIN products p ON p.product_id=pb.product_id
    JOIN production_consumptions pc ON pc.production_batch_id=pb.production_batch_id
    WHERE pb.batch_number LIKE 'PREOPEN-%'
    GROUP BY pb.production_batch_id, p.stock_item_id, pb.produced_quantity
)
UPDATE inventory_lots il SET unit_cost=bc.unit_cost
FROM batch_costs bc
JOIN production_batches pb ON pb.production_batch_id=bc.production_batch_id
JOIN products p ON p.product_id=pb.product_id
WHERE il.stock_item_id=bc.stock_item_id AND il.lot_code='PROD-OPENING-' || p.sku;

WITH batch_costs AS (
    SELECT pb.production_batch_id,
           SUM(pc.quantity_used * pc.unit_cost) / NULLIF(pb.produced_quantity, 0) AS unit_cost
    FROM production_batches pb
    JOIN production_consumptions pc ON pc.production_batch_id=pb.production_batch_id
    WHERE pb.batch_number LIKE 'PREOPEN-%'
    GROUP BY pb.production_batch_id, pb.produced_quantity
)
UPDATE stock_movements sm SET unit_cost=bc.unit_cost
FROM batch_costs bc
WHERE sm.source_type='PRODUCTION_BATCH' AND sm.source_id=bc.production_batch_id AND sm.movement_type='PRODUCTION_OUTPUT';
